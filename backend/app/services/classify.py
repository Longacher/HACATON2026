"""Автоклассификация свободного текста по ключевым словам (ТЗ 4.5, «Потенциал»).

Эвристика не заменяет оператора: он всегда может изменить категорию при приёме.
ML-модель — простой шаг на замену этой эвристики в будущем.
"""

CATEGORY_KEYWORDS = {
    "Травля и оскорбления": [
        "травл", "обзыва", "высмеив", "оскорбл", "издева", "булл", "булинг", "затравл",
        "смеются надо мной", "не дают проходу",
    ],
    "Конфликт с одноклассниками": [
        "одноклассник", "класс", "ссора с ребятами", "не понимают",
    ],
    "Кибербуллинг": [
        "кибер", "интернет", "сети", "соцсет", "чат", "телеграм", "переписк", "голосовые",
        "мемы", "фото в сеть", "пранк",
    ],
    "Давление и угрозы": [
        "угроз", "давл", "заставл", "шантаж", "пуга", "боюсь", "страшно", "принужд",
    ],
    "Конфликт с учителем": [
        "учител", "преподавател", "педагог оби", "заниж",
    ],
    "Конфликт с родителями": [
        "родител", "мама", "папа", "дома сканда", "ругает", "не понимают родители",
    ],
    "Вопрос юридического характера": [
        "юрид", "закон", "право", "суд", "адвокат", "штраф", "документ", "договор",
    ],
}


def suggest_category_name(text: str, answers: dict | None = None) -> str | None:
    """Возвращает название категории-кандидата или None."""
    haystack = (text or "").lower() + " "
    for v in (answers or {}).values():
        if isinstance(v, str):
            haystack += v.lower() + " "
    best = None
    best_score = 0
    for name, keywords in CATEGORY_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in haystack)
        if score > best_score:
            best_score = score
            best = name
    # «Не знаю, как назвать» НЕ присваиваем автоматически: свободный текст остаётся без
    # категории, пока оператор не решит.
    return best if best_score > 0 else None